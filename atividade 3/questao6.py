ingredientes = ["farinha", "açúcar", "ovos", "leite"]
print("Lista inicial:", ingredientes)

# Adiciona um novo ingrediente ao final
ingredientes.append("fermento")
print("Depois de adicionar ao final:", ingredientes)

# Insere um ingrediente em uma posição específica (ex: posição 1)
ingredientes.insert(1, "manteiga")
print("Depois de inserir na posição 1:", ingredientes)

# Remove um ingrediente pelo valor
ingredientes.remove("leite")
print("Depois de remover 'leite':", ingredientes)